/// Bỏ dấu tiếng Việt và chữ hoa, để tìm "viet" ra "Việt Nam".
String foldDiacritics(String text) {
  const groups = {
    'a': 'àáạảãâầấậẩẫăằắặẳẵåä',
    'e': 'èéẹẻẽêềếệểễë',
    'i': 'ìíịỉĩï',
    'o': 'òóọỏõôồốộổỗơờớợởỡö',
    'u': 'ùúụủũưừứựửữü',
    'y': 'ỳýỵỷỹ',
    'd': 'đ',
    'c': 'ç',
  };
  final buffer = StringBuffer();
  for (final rune in text.toLowerCase().runes) {
    final char = String.fromCharCode(rune);
    final plain = groups.entries
        .where((group) => group.value.contains(char))
        .map((group) => group.key)
        .firstOrNull;
    buffer.write(plain ?? char);
  }
  return buffer.toString();
}
